pub(super) fn validate_profile(profile: &LoadedProfile) -> Result<()> {
    let _ = profile_requires_local_keycloak(profile)?;
    Ok(())
}

fn profile_requires_local_keycloak(profile: &LoadedProfile) -> Result<bool> {
    let Some(activation) = &profile.definition.gateway_activation else {
        return Ok(false);
    };
    let control_plane_path = profile.resolve(&activation.control_plane);
    if !control_plane_path.exists() {
        return Ok(false);
    }
    let text = fs::read_to_string(&control_plane_path).with_context(|| {
        format!(
            "reading gateway control plane {} while detecting the local Keycloak requirement",
            control_plane_path.display()
        )
    })?;
    let control_plane: GatewayControlPlane = serde_json::from_str(&text).with_context(|| {
        format!(
            "decoding gateway control plane {} while detecting the local Keycloak requirement",
            control_plane_path.display()
        )
    })?;
    if !control_plane_declares_local_keycloak(&control_plane) {
        return Ok(false);
    }
    ensure!(
        profile.definition.kubernetes.local_cluster.is_some(),
        "deployment profile {} configures a local-development Keycloak identity provider but does not manage a local k3d cluster; local Keycloak is confined to disposable local-cluster profiles",
        profile.definition.name
    );
    Ok(true)
}

fn control_plane_declares_local_keycloak(control_plane: &GatewayControlPlane) -> bool {
    control_plane.identity_providers.iter().any(|provider| {
        provider.metadata.get("provider").and_then(Value::as_str)
            == Some(LOCAL_KEYCLOAK_METADATA_PROVIDER)
            && provider.metadata.get("purpose").and_then(Value::as_str)
                == Some(LOCAL_KEYCLOAK_METADATA_PURPOSE)
    })
}

pub(super) fn ensure(profile: &LoadedProfile) -> Result<()> {
    if !profile_requires_local_keycloak(profile)? {
        return Ok(());
    }
    let lock = StateLock::acquire()?;
    container::ensure(profile, &lock)
}

pub(super) fn stop(profile: &LoadedProfile) -> Result<()> {
    if !profile_requires_local_keycloak(profile)? {
        return Ok(());
    }
    let lock = StateLock::acquire()?;
    container::stop(&lock)
}

pub(super) fn delete(profile: &LoadedProfile) -> Result<()> {
    if !profile_requires_local_keycloak(profile)? {
        return Ok(());
    }
    let lock = StateLock::acquire()?;
    container::delete(&lock)?;
    tls::remove_material(&profile.repository, &lock)
}

/// Holds the cross-process state lock while the caller reads generated bytes.
/// This prevents another worktree from rotating TLS and reconciling the shared
/// container between generation and Gateway ConfigMap construction.
pub(super) struct GeneratedPublicFiles {
    paths: BTreeMap<String, PathBuf>,
    _lock: Option<StateLock>,
}

impl GeneratedPublicFiles {
    pub(super) fn path(&self, key: &str) -> Option<&PathBuf> {
        self.paths.get(key)
    }
}

pub(super) fn ensure_generated_public_files(
    profile: &LoadedProfile,
) -> Result<GeneratedPublicFiles> {
    ensure_generated_public_files_with(profile, container::ensure)
}

fn ensure_generated_public_files_with<F>(
    profile: &LoadedProfile,
    reconcile: F,
) -> Result<GeneratedPublicFiles>
where
    F: FnOnce(&LoadedProfile, &StateLock) -> Result<()>,
{
    let Some(activation) = &profile.definition.gateway_activation else {
        return Ok(GeneratedPublicFiles {
            paths: BTreeMap::new(),
            _lock: None,
        });
    };
    if activation.generated_public_files.is_empty() {
        return Ok(GeneratedPublicFiles {
            paths: BTreeMap::new(),
            _lock: None,
        });
    }

    let lock = StateLock::acquire()?;
    let mut paths = BTreeMap::new();
    let mut requires_local_keycloak = false;
    for (key, generated) in &activation.generated_public_files {
        let path = match generated.kind {
            GeneratedPublicFileKind::LocalKeycloakCa => {
                requires_local_keycloak = true;
                ensure_generation(&profile.repository, &lock)?.ca_path
            }
        };
        paths.insert(key.clone(), path);
    }
    if requires_local_keycloak {
        reconcile(profile, &lock)?;
    }
    Ok(GeneratedPublicFiles {
        paths,
        _lock: Some(lock),
    })
}
